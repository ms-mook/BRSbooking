function row(ts, date, who, room, st, slots) {
  const [f, l, pos] = PEOPLE[who];
  const r = [ts, date, f, l, pos, room, st];
  const cols = { '06:00-08:30': 7, '06:00-11:00': 7, '08:30-12:30': 8, '06:00-12:00': 8, '12:30-16:30': 9, '06:00-16:00': 9, '16:30-สิ้นสุด': 10, '06:00-สิ้นสุด': 11 };
  slots.forEach((s) => { while (r.length <= cols[s]) r.push(''); r[cols[s]] = s; });
  return r;
}
